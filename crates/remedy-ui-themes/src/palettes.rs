//! The shared Remedy palettes, generated from RemedyAI's `desktop/src/themes.ts` (the palettes
//! Portal, Hearth and FreeSpeak skins share). Regenerate rather than edit by hand.

/// One palette: id, display name, whether it is dark, and its colors as hex.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Palette {
    /// Stable id (`forest`, `light`, …).
    pub id: &'static str,
    /// Display name.
    pub name: &'static str,
    /// A dark palette.
    pub dark: bool,
    /// `--bg-primary`.
    pub bg: &'static str,
    /// `--bg-secondary`.
    pub panel: &'static str,
    /// `--bg-tertiary`.
    pub card: &'static str,
    /// `--border`.
    pub line: &'static str,
    /// `--accent`.
    pub accent: &'static str,
    /// `--text-primary`.
    pub text: &'static str,
    /// `--text-secondary`.
    pub muted: &'static str,
    /// `--text-muted`.
    pub faint: &'static str,
    /// `--accent-hover`.
    pub accent_hover: &'static str,
    /// `--success`.
    pub ok: &'static str,
    /// `--error`.
    pub danger: &'static str,
    /// `--warning`.
    pub warn: &'static str,
}

