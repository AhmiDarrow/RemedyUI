//! Compiling `.rui` files to Rust at build time, so release builds pay nothing for markup.
//!
//! In `build.rs`:
//!
//! ```no_run
//! remedy_ui_rui::build::compile_dir("ui", &[]).expect("the app's .rui files compile");
//! ```
//!
//! Compiled code reaches the markup runtime through the facade, `remedy_ui::markup`
//! ([`FACADE_ROOT`]), so an app that depends only on `remedy-ui` (feature `markup`) needs
//! nothing else. An app that depends on `remedy-ui-rui` directly compiles with
//! [`DIRECT_ROOT`] ([`compile_in`], [`build::compile_dir_in`]).
//!
//! and in the app, for `ui/settings_voice.rui`:
//!
//! ```ignore
//! mod settings_voice {
//!     include!(concat!(env!("OUT_DIR"), "/rui/settings_voice.rs"));
//! }
//! let b = settings_voice::Bindings { noise_suppression: noise, /* ... */ };
//! let el = settings_voice::build(&ui, &b, &|s| catalog.translate(&ui, s));
//! ```
//!
//! Each compiled file has a `Bindings` struct with a field for every signal and command it
//! uses (their types follow from where they are used), `build`, and `FILE` and `SOURCE`
//! for loading a person's own version of the file through [`crate::Layouts`] with
//! `Bindings::scope`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::spec::{self, Kind, Param, Spec};
use crate::syntax::{Markup, Node, RuiError, Value};

/// One of the app's own elements, for the compiler: what it takes and the Rust function
/// that builds it (`fn(&Ui, remedy_ui_rui::Call) -> El`, by path).
#[derive(Clone, Debug)]
pub struct Custom {
    /// Its name in markup.
    pub name: String,
    /// What it takes.
    pub params: Vec<Param>,
    /// It holds children.
    pub children: bool,
    /// The path of its builder, such as `crate::ui::fretboard`.
    pub path: String,
}

/// The path compiled code reaches the markup runtime by when the app uses the facade.
pub const FACADE_ROOT: &str = "::remedy_ui::markup";

/// The path compiled code reaches the markup runtime by when the app depends on this crate.
pub const DIRECT_ROOT: &str = "::remedy_ui_rui";

/// The name compiled code gives the runtime's root (a `use` at the top of each file).
const ROOT: &str = "remedy_ui_markup";

const RT: &str = "remedy_ui_markup::rt";

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while",
    "abstract", "become", "box", "do", "final", "gen", "macro", "override", "priv", "try", "typeof",
    "unsized", "virtual", "yield",
];

fn field(name: &str) -> String {
    if KEYWORDS.contains(&name) { format!("r#{name}") } else { name.to_owned() }
}

fn lit(s: &str) -> String {
    format!("{s:?}")
}

fn f64_lit(n: f64) -> String {
    format!("{n:?}_f64")
}

fn f32_lit(n: f64) -> String {
    format!("{n:?}_f32")
}

/// Compiles one file to Rust that reaches the runtime through the facade ([`FACADE_ROOT`]).
/// `customs` are the app's own elements.
pub fn compile(file: &str, source: &str, customs: &[Custom]) -> Result<String, RuiError> {
    compile_in(FACADE_ROOT, file, source, customs)
}

/// Compiles one file to Rust that reaches the runtime at `root` (a path to this crate, such as
/// [`FACADE_ROOT`] or [`DIRECT_ROOT`]). `customs` are the app's own elements.
pub fn compile_in(root: &str, file: &str, source: &str, customs: &[Custom]) -> Result<String, RuiError> {
    let markup = Markup::parse(file, source)?;
    let mut specs: Vec<Spec> = spec::built_in();
    for c in customs {
        specs.retain(|s| s.name != c.name);
        specs.push(Spec { name: c.name.clone(), params: c.params.clone(), children: c.children });
    }
    let uses = spec::check(&markup, &specs)?;
    let mut out = String::new();
    let _ = writeln!(out, "// Generated by remedy-ui-rui from {file}. Edit the .rui file, not this one.");
    let _ = writeln!(out, "#[allow(unused_imports)]\nuse {root} as {ROOT};\n");
    let _ = writeln!(out, "/// What `{file}` uses: a field for each signal and command it names.");
    let _ = writeln!(out, "#[allow(missing_docs)]\n#[derive(Clone)]\npub struct Bindings {{");
    for (name, kind) in &uses.signals {
        let ty = kind.signal_type().unwrap_or("()");
        let _ = writeln!(out, "    pub {}: {RT}::reactive::Signal<{ty}>,", field(name));
    }
    for name in &uses.commands {
        let _ = writeln!(out, "    pub {}: ::std::rc::Rc<dyn Fn()>,", field(name));
    }
    let _ = writeln!(out, "}}\n");
    let _ = writeln!(out, "impl Bindings {{");
    let _ = writeln!(
        out,
        "    /// The same names as a scope, translated by `t`, to load a person's own version of the file."
    );
    let _ = writeln!(
        out,
        "    pub fn scope(&self, t: impl Fn(&str) -> String + 'static) -> remedy_ui_markup::Scope {{"
    );
    let _ = write!(out, "        remedy_ui_markup::Scope::new().translator(t)");
    for (name, kind) in &uses.signals {
        let method = match kind {
            Kind::Text => "text",
            Kind::Flag => "flag",
            Kind::Number => "number",
            Kind::Choice => "choice",
            Kind::Items => "items",
            _ => "level",
        };
        let _ = write!(out, "\n            .{method}({}, self.{})", lit(name), field(name));
    }
    for name in &uses.commands {
        let _ = write!(
            out,
            "\n            .bind({}, remedy_ui_markup::Binding::Command(self.{}.clone()))",
            lit(name),
            field(name)
        );
    }
    let _ = writeln!(out, "\n    }}\n}}\n");
    let _ = writeln!(out, "/// The file's name.\npub const FILE: &str = {};", lit(file));
    let _ = writeln!(out, "/// The file as written.\npub const SOURCE: &str = {};\n", lit(source));
    let _ = writeln!(out, "/// Builds the file's elements; `t` translates `@t(\"...\")`.");
    let _ = writeln!(out, "#[allow(unused_variables, clippy::redundant_clone)]");
    let _ = writeln!(
        out,
        "pub fn build(ui: &{RT}::view::Ui, b: &Bindings, t: &dyn Fn(&str) -> String) -> {RT}::view::El {{"
    );
    let mut g = Gen { specs: &specs, customs, out: String::new() };
    g.node(&markup.root, 1);
    out.push_str(&g.out);
    let _ = writeln!(out, "\n}}");
    Ok(out)
}

struct Gen<'a> {
    specs: &'a [Spec],
    customs: &'a [Custom],
    out: String,
}

impl Gen<'_> {
    fn pad(&mut self, depth: usize) {
        for _ in 0..depth {
            self.out.push_str("    ");
        }
    }

    /// The Rust for an argument as fixed text.
    fn label(v: Option<&Value>) -> String {
        match v {
            Some(Value::Str(s)) => format!("{}.to_owned()", lit(s)),
            Some(Value::Translate(s)) => format!("t({})", lit(s)),
            _ => "::std::string::String::new()".to_owned(),
        }
    }

    fn common(n: &Node) -> String {
        let mut parts: Vec<String> = Vec::new();
        for a in &n.args {
            let v = match (a.name.as_str(), &a.value) {
                ("gap" | "padding", Value::Token(t)) => {
                    format!("Some({RT}::Space::Units({}))", spec::space_units(t).unwrap_or(0))
                }
                ("gap" | "padding", Value::Number(px)) => format!("Some({RT}::Space::Px({}))", f32_lit(*px)),
                ("grow", Value::Number(g)) => format!("Some({})", f32_lit(*g)),
                ("fill_width", Value::Bool(b)) => b.to_string(),
                ("variant", Value::Token(v) | Value::Str(v)) => format!("Some({})", lit(v)),
                ("align", Value::Token(w) | Value::Str(w)) => format!("{RT}::align({})", lit(w)),
                ("justify", Value::Token(w) | Value::Str(w)) => format!("{RT}::justify({})", lit(w)),
                ("visible", Value::Signal(s)) => format!("Some(b.{})", field(s)),
                _ => continue,
            };
            parts.push(format!("{}: {v}", a.name));
        }
        if parts.is_empty() {
            format!("{RT}::Common::default()")
        } else {
            format!("{RT}::Common {{ {}, ..::core::default::Default::default() }}", parts.join(", "))
        }
    }

    fn bound(v: &Value) -> String {
        let b = "remedy_ui_markup::Bound";
        match v {
            Value::Str(s) => format!("{b}::Label({}.to_owned())", lit(s)),
            Value::Translate(s) => format!("{b}::Label(t({}))", lit(s)),
            Value::Range(a, z) => format!("{b}::Range({}, {})", f64_lit(*a), f64_lit(*z)),
            Value::Number(n) => format!("{b}::Count({})", f64_lit(*n)),
            Value::Bool(x) => format!("{b}::Switch({x})"),
            Value::Token(t) => match spec::space_units(t) {
                Some(u) => format!("{b}::Space({RT}::Space::Units({u}))"),
                None => format!("{b}::Word({}.to_owned())", lit(t)),
            },
            Value::Signal(s) => format!("{b}::Binding(remedy_ui_markup::Binding::Text(b.{}))", field(s)),
            Value::Command(c) => {
                format!("{b}::Binding(remedy_ui_markup::Binding::Command(b.{}.clone()))", field(c))
            }
        }
    }

    fn node(&mut self, n: &Node, depth: usize) {
        let arg = |name: &str| n.arg(name).map(|a| &a.value);
        let sig = |name: &str| match arg(name) {
            Some(Value::Signal(s)) => Some(format!("b.{}", field(s))),
            _ => None,
        };
        let label = |name: &str| Self::label(arg(name));
        let text = Self::label(arg("text"));
        let range = match arg("range") {
            Some(Value::Range(a, z)) => (*a, *z),
            _ => (0.0, 1.0),
        };
        let step = match arg("step") {
            Some(Value::Number(s)) => f64_lit(*s),
            _ => f64_lit(spec_default_step(range)),
        };
        let custom = self.customs.iter().find(|c| c.name == n.name);
        let w = format!("{RT}::w");
        let el: String = if let Some(c) = custom {
            let mut call = "remedy_ui_markup::Call::new()".to_owned();
            for a in &n.args {
                if spec::COMMON.iter().any(|p| p.name == a.name) {
                    continue;
                }
                let v = match &a.value {
                    // Signals as bindings of the kind they are used as.
                    Value::Signal(s) => {
                        let kind = self
                            .specs
                            .iter()
                            .find(|sp| sp.name == n.name)
                            .and_then(|sp| sp.params.iter().find(|p| p.name == a.name))
                            .map_or(Kind::Text, |p| p.kind);
                        let variant = match kind {
                            Kind::Flag => "Flag",
                            Kind::Number => "Number",
                            Kind::Choice => "Choice",
                            Kind::Items => "Items",
                            Kind::Level => "Level",
                            _ => "Text",
                        };
                        format!(
                            "remedy_ui_markup::Bound::Binding(remedy_ui_markup::Binding::{variant}(b.{}))",
                            field(s)
                        )
                    }
                    other => Self::bound(other),
                };
                call.push_str(&format!(".arg({}, {v})", lit(&a.name)));
            }
            // Children go in as built elements.
            let mut kids = String::new();
            for k in &n.children {
                let mut sub = Gen { specs: self.specs, customs: self.customs, out: String::new() };
                sub.node(k, depth + 2);
                kids.push_str(&format!(".child({})", sub.out.trim()));
            }
            format!("{}(ui, {call}{kids})", c.path)
        } else {
            let textual = |el: String| match sig("text") {
                Some(s) => format!("{RT}::live_text({el}, {s})"),
                None => el,
            };
            let flag =
                |name: &str| sig(name).unwrap_or_else(|| format!("{RT}::reactive::Signal::new(false)"));
            match n.name.as_str() {
                "column" | "row" | "wrap" | "card" | "scroll" | "spacer" => format!("{w}::{}(ui)", n.name),
                "section" => format!("{w}::section(ui, &{})", label("title")),
                "divider" => {
                    let v = matches!(arg("vertical"), Some(Value::Bool(true)));
                    format!("{w}::divider(ui, {v})")
                }
                "text" | "badge" => textual(format!("{w}::{}(ui, {text})", n.name)),
                "heading" => {
                    let level = match arg("level") {
                        Some(Value::Number(l)) => *l,
                        _ => 1.0,
                    };
                    textual(format!("{w}::heading(ui, {RT}::heading_level({}), {text})", f64_lit(level)))
                }
                "button" | "link" => {
                    let f = match arg("on_press") {
                        Some(Value::Command(c)) => format!("b.{}.clone()", field(c)),
                        _ => "::std::rc::Rc::new(|| {})".to_owned(),
                    };
                    format!("{{ let f = {f}; {w}::{}(ui, {}, move || f()) }}", n.name, label("label"))
                }
                "switch" | "check" => format!("{w}::{}(ui, {}, {})", n.name, label("label"), flag("checked")),
                "toggle_button" | "lamp" => {
                    format!("{w}::{}(ui, {}, {})", n.name, label("label"), flag("on"))
                }
                "chip" => format!("{w}::chip(ui, {}, {})", label("label"), flag("selected")),
                "select" | "radio_group" | "segmented" => {
                    let items = sig("items").unwrap_or_default();
                    let selected = sig("selected").unwrap_or_default();
                    let list =
                        if n.name == "select" { "list.to_vec()" } else { &format!("&{RT}::strs(list)") };
                    let common = Self::common(n);
                    self.pad(depth);
                    let _ = write!(
                        self.out,
                        "{{ let ui2 = ui.clone(); let l = {}; let selected = {selected}; {RT}::with_items(ui, &{common}, {items}, move |list| {w}::{}(&ui2, l.clone(), {list}, selected)) }}",
                        label("label"),
                        n.name,
                    );
                    return;
                }
                "slider" | "stepper" => format!(
                    "{w}::{}(ui, {}, {}, {}, {}, {step})",
                    n.name,
                    label("label"),
                    sig("value").unwrap_or_else(|| format!("{RT}::reactive::Signal::new(0.0)")),
                    f64_lit(range.0),
                    f64_lit(range.1),
                ),
                "progress" => format!(
                    "{w}::progress(ui, {}, {})",
                    label("label"),
                    sig("value").unwrap_or_else(|| format!("{RT}::reactive::Signal::new(None)"))
                ),
                "spinner" => format!("{w}::spinner(ui, {})", label("label")),
                "empty_state" => format!("{w}::empty_state(ui, {}, {})", label("title"), label("hint")),
                "text_input" | "text_area" => {
                    let field_el = format!("{w}::{}(ui, {})", n.name, label("label"));
                    match sig("value") {
                        Some(s) => format!("{RT}::bound_field({field_el}, {s})"),
                        None => format!("{{ let f = {field_el}; f.set_value(&{}); f.el() }}", label("value")),
                    }
                }
                _ => format!("{w}::column(ui)"),
            }
        };
        let common = Self::common(n);
        self.pad(depth);
        let _ = write!(self.out, "{RT}::finish(ui, {el}, &{common}, vec![");
        if custom.is_none() && !n.children.is_empty() {
            self.out.push('\n');
            for c in &n.children {
                self.node(c, depth + 1);
                self.out.push_str(",\n");
            }
            self.pad(depth);
        }
        self.out.push_str("])");
    }
}

fn spec_default_step(range: (f64, f64)) -> f64 {
    spec::default_step(range.0, range.1)
}

/// The build-script side: compile a folder of `.rui` files.
pub mod build {
    use super::*;

    /// Compiles every `.rui` file in `dir` (relative to the crate) to
    /// `$OUT_DIR/rui/<name>.rs`, and tells Cargo to rebuild when one changes. `customs` are
    /// the app's own elements.
    pub fn compile_dir(dir: impl AsRef<Path>, customs: &[Custom]) -> Result<Vec<PathBuf>, BuildError> {
        compile_dir_in(FACADE_ROOT, dir, customs)
    }

    /// [`compile_dir`] for an app that reaches the runtime at `root` ([`DIRECT_ROOT`] when it
    /// depends on `remedy-ui-rui` itself).
    pub fn compile_dir_in(
        root: &str,
        dir: impl AsRef<Path>,
        customs: &[Custom],
    ) -> Result<Vec<PathBuf>, BuildError> {
        let out = PathBuf::from(std::env::var_os("OUT_DIR").ok_or(BuildError::NoOutDir)?).join("rui");
        compile_dir_to(root, dir.as_ref(), &out, customs, true)
    }

    /// Compiles every `.rui` file in `dir` into `out`, reaching the runtime at `root`. With
    /// `cargo`, prints Cargo's rebuild lines.
    pub fn compile_dir_to(
        root: &str,
        dir: &Path,
        out: &Path,
        customs: &[Custom],
        cargo: bool,
    ) -> Result<Vec<PathBuf>, BuildError> {
        std::fs::create_dir_all(out).map_err(|e| BuildError::Io(out.to_owned(), e))?;
        if cargo {
            println!("cargo:rerun-if-changed={}", dir.display());
        }
        let mut entries: Vec<PathBuf> = std::fs::read_dir(dir)
            .map_err(|e| BuildError::Io(dir.to_owned(), e))?
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.extension().is_some_and(|x| x == "rui"))
            .collect();
        entries.sort();
        let mut written = Vec::new();
        for path in entries {
            if cargo {
                println!("cargo:rerun-if-changed={}", path.display());
            }
            let source = std::fs::read_to_string(&path).map_err(|e| BuildError::Io(path.clone(), e))?;
            let name = path.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
            let rust = compile_in(root, &name, &source, customs).map_err(BuildError::Rui)?;
            let stem = path
                .file_stem()
                .map(|s| s.to_string_lossy().replace(['-', ' ', '.'], "_"))
                .unwrap_or_default();
            let target = out.join(format!("{stem}.rs"));
            // Unchanged output keeps its timestamp, so nothing downstream rebuilds.
            if std::fs::read_to_string(&target).ok().as_deref() != Some(rust.as_str()) {
                std::fs::write(&target, rust).map_err(|e| BuildError::Io(target.clone(), e))?;
            }
            written.push(target);
        }
        Ok(written)
    }

    /// Why compiling a folder failed.
    #[derive(Debug)]
    #[non_exhaustive]
    pub enum BuildError {
        /// Not running in a build script.
        NoOutDir,
        /// A file could not be read or written.
        Io(PathBuf, std::io::Error),
        /// A file is not valid markup.
        Rui(RuiError),
    }

    impl std::fmt::Display for BuildError {
        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            match self {
                BuildError::NoOutDir => f.write_str("OUT_DIR is not set; call this from build.rs"),
                BuildError::Io(p, e) => write!(f, "{}: {e}", p.display()),
                BuildError::Rui(e) => write!(f, "{e}"),
            }
        }
    }

    impl std::error::Error for BuildError {}
}
